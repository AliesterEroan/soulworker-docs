#!/usr/bin/env python3
"""Stage the files the Tauri shell compiles: frontend/index.html and the Windows icon.

The shell carries the single-file build, so run build_standalone.py first. This script refuses to
stage a stale copy rather than shipping an exe around an old app, and it never runs the builder
itself - one command per step, so what happened is always visible.

Run after every change to the app, from SoulWorkerDocs:  python shell\\prepare_frontend.py
See shell\\BUILD.md for the commands that produce the executable.
"""

import pathlib
import shutil
import sys

HERE = pathlib.Path(__file__).resolve().parent
DOCSAPP = HERE.parent
STANDALONE = DOCSAPP / "SoulWorkerDocs-standalone.html"
ICON = DOCSAPP / "icon.ico"
ICON_PNG = DOCSAPP / "icon.png"
FRONTEND = HERE / "frontend" / "index.html"
ICONS = HERE / "src-tauri" / "icons"

MARKER = "<!-- Generated by build_standalone.py"


def newest_source():
    return max((p.stat().st_mtime for p in
                (DOCSAPP / "SoulWorkerDocs.html", DOCSAPP / "data.js",
                 DOCSAPP / "build_standalone.py",
                 DOCSAPP / "vendor" / "xlsx.full.min.js",
                 DOCSAPP / "fonts" / "plus-jakarta-sans-var.woff2",
                 DOCSAPP / "fonts" / "jetbrains-mono-var.woff2")))


def main():
    if not STANDALONE.is_file():
        raise SystemExit("no %s - run python build_standalone.py in %s first"
                         % (STANDALONE.name, DOCSAPP))
    if STANDALONE.stat().st_mtime < newest_source():
        raise SystemExit("%s is older than the app source - run python build_standalone.py first"
                         % STANDALONE.name)
    for required in (ICON, ICON_PNG):
        if not required.is_file():
            raise SystemExit("no %s - run python make_icon.py first" % required)

    head = STANDALONE.read_text(encoding="utf-8", errors="replace")[:len(MARKER)]
    if head != MARKER:
        raise SystemExit("%s does not start with the generated marker - it is not a build output"
                         % STANDALONE.name)

    FRONTEND.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(STANDALONE, FRONTEND)
    ICONS.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ICON, ICONS / "icon.ico")
    shutil.copyfile(ICON_PNG, ICONS / "icon.png")

    print("frontend : %s <- %s (%d bytes)" % (FRONTEND, STANDALONE.name, FRONTEND.stat().st_size))
    print("icons    : %s (%d bytes) + icon.png for 'cargo tauri icon'"
          % (ICONS / "icon.ico", (ICONS / "icon.ico").stat().st_size))
    print("next     : python shell\\build_release.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
